local dtAvg = 1 / 60

local filteredPitch = 0.0
local filteredRoll  = 0.0

local prevSusp = nil

-- Suspension bob
local suspensionBob = 0.0

-- Head rotation
local headYaw   = 0.0
local headRoll  = 0.0
local headPitch = 0.0

-- Position inertia
local ieLateral  = ie_new()
local ieForward  = ie_new()
local ieVertical = ie_new()

local curLateral  = 0.0
local curForward  = 0.0
local curVertical = 0.0


