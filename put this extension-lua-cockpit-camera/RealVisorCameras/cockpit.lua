-- ========================================================================
-- Exact exponential damper
-- ========================================================================

local LN2 = 0.69314718056

local function damper_exact(x, goal, halflife, dt)
  halflife = math.max(halflife, 0.0001)

  return goal
    + (x - goal)
    * math.exp(-(LN2 * dt) / halflife)
end


-- ========================================================================
-- Inertial easing
-- ========================================================================

local function ie_new()
  return {
    et = 1.0,
    es = 0.0,
    eo = 0.0,
    prev = nil,
    vel = 0.0
  }
end


local function ie_eval(et, es)

  if et >= 1.0 then
    return es
  end

  return es * (3 * et * et - 2 * et * et * et)
end


local function ie_eval_vel(et, es, blendtime)

  if et >= 1.0 then
    return 0.0
  end

  return es * (6 * et - 6 * et * et) / blendtime
end


local function ie_solve(x, v, overshoot, eps)

  overshoot = overshoot or 0.05
  eps = eps or 1e-8

  if math.abs(v) < eps then
    return 0.0, x
  end

  if x < 0.0 then

    local t, s = ie_solve(
      -x,
      -v,
      overshoot,
      eps
    )

    return t, -s
  end

  local disc =
    math.max(
      (6 * x - v) * (6 * x - v)
      + 8 * v * v,
      eps
    )

  local sq = math.sqrt(disc)

  local t0 =
    (v - 6 * x + sq)
    / (4 * v)

  local t1 =
    (v - 6 * x - sq)
    / (4 * v)

  local t =
    (-0.5 > t1 and t1 > -(0.5 + overshoot))
    and t1
    or t0

  local vt =
    (t < 1.0)
    and (6 * t - 6 * t * t)
    or 0.0

  local s =
    math.abs(vt) < eps
    and 0.0
    or v / vt

  return t, s
end


local function ie_update(
  state,
  current,
  target,
  blendtime,
  dt
)

  blendtime = math.max(blendtime, 1e-4)

  if state.prev ~= target then

    local dist = target - current

    state.et, state.es =
      ie_solve(
        dist,
        state.vel * blendtime
      )

    state.eo =
      current - ie_eval(
        state.et,
        state.es
      )

    state.prev = target
  end

  state.et =
    state.et + dt / blendtime

  local value =
    state.eo
    + ie_eval(
      state.et,
      state.es
    )

  state.vel =
    ie_eval_vel(
      state.et,
      state.es,
      blendtime
    )

  return value
end


